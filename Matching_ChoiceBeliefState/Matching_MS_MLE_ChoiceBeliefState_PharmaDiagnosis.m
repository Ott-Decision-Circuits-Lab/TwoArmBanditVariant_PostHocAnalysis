    ChoiceStickinessErrorBar(iSession)...
        = errorbar(SessionChoiceStickinessMLEAxes,...
                   iSession,...
                   MLEEstimates(4),...
                   Model.ParameterStandardError(4),...
                   'Marker', 'o',...
                   'Color', 'k');
    

    % choice stickiness
    ChoiceForgettingRateErrorBar(iSession)...
        = errorbar(SessionChoiceForgettingRateMLEAxes,...
                   iSession,...
                   MLEEstimates(5),...
                   Model.ParameterStandardError(5),...
                   'Marker', 'o',...
                   'Color', 'k');
    

