    StateInverseTemperatureErrorBar(iSession)...
        = errorbar(SessionStateInverseTemperatureMLEAxes,...
                   iSession,...
                   MLEEstimates(6),...
                   Model.ParameterStandardError(6),...
                   'Marker', 'o',...
                   'Color', 'k');
    

