        = errorbar(SessionInverseTemperatureMLEAxes,...
                   iSession,...
                   MLEEstimates(2),...
                   Model.ParameterStandardError(2),...
                   'Marker', 'o',...
                   'Color', 'k');
    
    % forgetting rate
    ForgettingRateErrorBar(iSession)...
        = errorbar(SessionForgettingRateMLEAxes,...
                   iSession,...
                   MLEEstimates(3),...
                   Model.ParameterStandardError(3),...
                   'Marker', 'o',...
                   'Color', 'k');
    
